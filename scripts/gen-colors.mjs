#!/usr/bin/env node
/** Generate atomic palette scales (100–900) from brand hex anchors. */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/** @typedef {Record<string, string>} Palette */

export const WEIGHTS = [100, 200, 300, 400, 500, 600, 700, 800, 900];
/** Lightness offsets; 500 uses the input hex verbatim. */
export const OFFSETS = [0.35, 0.25, 0.15, 0.07, 0, -0.07, -0.15, -0.25, -0.35];

/** @type {Record<"day"|"night", Palette>} */
export const PALETTES = {
  day: {
    sky: "#EAF7FF",
    water: "#BFE7FF",
    grass: "#8FD694",
    sunlight: "#FFF4B1",
    bread: "#FFD39A",
    reeds: "#5B8E7D",
  },
  night: {
    sky: "#0B1026",
    water: "#1B2440",
    grass: "#4E5D94",
    sunlight: "#89C2D9",
    bread: "#CDB4DB",
    reeds: "#FFE5B4",
  },
};

/** colorsys rgb_to_hls / hls_to_rgb (H, L, S with L,S in 0–1). */
/**
 * @param {number} r @param {number} g @param {number} b  0–1
 * @returns {[number, number, number]}
 */
function rgbToHls(r, g, b) {
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const l = (min + max) / 2;
  if (min === max) return [0, l, 0];
  const d = max - min;
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  let h;
  if (max === r) h = ((g - b) / d + (g < b ? 6 : 0)) / 6;
  else if (max === g) h = ((b - r) / d + 2) / 6;
  else h = ((r - g) / d + 4) / 6;
  return [h, l, s];
}

/**
 * @param {number} h @param {number} l @param {number} s
 * @returns {[number, number, number]}
 */
function hlsToRgb(h, l, s) {
  if (s === 0) return [l, l, l];
  const hue2rgb = (p, q, t) => {
    let tt = t;
    if (tt < 0) tt += 1;
    if (tt > 1) tt -= 1;
    if (tt < 1 / 6) return p + (q - p) * 6 * tt;
    if (tt < 1 / 2) return q;
    if (tt < 2 / 3) return p + (q - p) * (2 / 3 - tt) * 6;
    return p;
  };
  const q = l < 0.5 ? l * (1 + s) : l + s - l * s;
  const p = 2 * l - q;
  return [hue2rgb(p, q, h + 1 / 3), hue2rgb(p, q, h), hue2rgb(p, q, h - 1 / 3)];
}

/**
 * @param {string} hex
 * @returns {Record<number, string>}
 */
export function makeScale(hex) {
  const raw = hex.replace("#", "");
  const n = parseInt(raw, 16);
  const r = ((n >> 16) & 255) / 255;
  const g = ((n >> 8) & 255) / 255;
  const b = (n & 255) / 255;
  const [h, l, s] = rgbToHls(r, g, b);
  /** @type {Record<number, string>} */
  const out = {};
  for (let i = 0; i < WEIGHTS.length; i++) {
    const w = WEIGHTS[i];
    if (w === 500) {
      out[w] = hex.toLowerCase();
      continue;
    }
    const L = Math.max(0.05, Math.min(0.95, l + OFFSETS[i]));
    const [rr, gg, bb] = hlsToRgb(h, L, s);
    const toByte = (x) => Math.round(Math.max(0, Math.min(1, x)) * 255);
    out[w] = `#${[rr, gg, bb].map((c) => toByte(c).toString(16).padStart(2, "0")).join("")}`;
  }
  return out;
}

/**
 * @param {Palette} palette
 * @returns {Record<string, Record<number, string>>}
 */
export function scalesForPalette(palette) {
  /** @type {Record<string, Record<number, string>>} */
  const out = {};
  for (const [name, hex] of Object.entries(palette)) {
    out[name] = makeScale(hex);
  }
  return out;
}

/**
 * @param {Record<string, Record<number, string>>} scales
 * @param {string} indent
 */
function emitScaleVars(scales, indent = "  ") {
  const lines = [];
  for (const name of Object.keys(scales)) {
    for (const w of WEIGHTS) {
      lines.push(`${indent}--${name}-${w}: ${scales[name][w]};`);
    }
  }
  return lines.join("\n");
}

/**
 * @param {Palette} palette
 */
function emitPropertyRegistration(palette) {
  return Object.keys(palette)
    .map(
      (name) =>
        `@property --${name}-500 { syntax: "<color>"; inherits: true; initial-value: ${palette[name].toLowerCase()}; }`,
    )
    .join("\n");
}

/** @param {Palette} day */
function emitCss(day) {
  const dayScales = scalesForPalette(PALETTES.day);
  const nightScales = scalesForPalette(PALETTES.night);

  return `/* Generated by scripts/gen-colors.mjs — do not edit by hand. */
/* Brand anchors (500) drive day/night transition; other weights are static per mode. */

${emitPropertyRegistration(day)}

/* Legacy animated slots → atomic 500 weights */
@property --brand-0 { syntax: "<color>"; inherits: true; initial-value: ${PALETTES.day.sky.toLowerCase()}; }
@property --brand-1 { syntax: "<color>"; inherits: true; initial-value: ${PALETTES.day.water.toLowerCase()}; }
@property --brand-2 { syntax: "<color>"; inherits: true; initial-value: ${PALETTES.day.grass.toLowerCase()}; }
@property --brand-3 { syntax: "<color>"; inherits: true; initial-value: ${PALETTES.day.sunlight.toLowerCase()}; }
@property --brand-4 { syntax: "<color>"; inherits: true; initial-value: ${PALETTES.day.bread.toLowerCase()}; }
@property --brand-5 { syntax: "<color>"; inherits: true; initial-value: ${PALETTES.day.reeds.toLowerCase()}; }

:root {
${emitScaleVars(dayScales)}

  --brand-0: var(--sky-500);
  --brand-1: var(--water-500);
  --brand-2: var(--grass-500);
  --brand-3: var(--sunlight-500);
  --brand-4: var(--bread-500);
  --brand-5: var(--reeds-500);
}

[data-time="night"] {
${emitScaleVars(nightScales)}

  --brand-0: var(--sky-500);
  --brand-1: var(--water-500);
  --brand-2: var(--grass-500);
  --brand-3: var(--sunlight-500);
  --brand-4: var(--bread-500);
  --brand-5: var(--reeds-500);
}
`;
}

/** Self-check: every 500 weight matches its palette anchor. */
export function assertScales() {
  for (const [mode, palette] of Object.entries(PALETTES)) {
    const scales = scalesForPalette(palette);
    for (const [name, hex] of Object.entries(palette)) {
      const got = scales[name][500];
      if (got !== hex.toLowerCase()) {
        throw new Error(`${mode}.${name} 500=${got} expected ${hex.toLowerCase()}`);
      }
    }
  }
}

const outPath = join(dirname(fileURLToPath(import.meta.url)), "..", "styles", "tokens.css");

export function writeTokensCss() {
  assertScales();
  writeFileSync(outPath, emitCss(PALETTES.day), "utf8");
  return outPath;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const path = writeTokensCss();
  console.log(`Wrote ${path}`);
}
